/**
 * Render deployment overlays from `config/ui/deployment/values.yaml`.
 *
 * This template is config-driven: building a UI means editing `config/`,
 * not code. Deployment was the hole in that — changing a replica count or
 * a memory limit meant editing a manifest, which is code.
 *
 * So `config/ui/deployment/values.yaml` becomes the source of truth and this
 * renders the patches from it. Not Helm: the platform's control plane
 * deploys by downloading and patching this repo's kustomize overlay, so
 * the output has to stay a kustomize overlay.
 *
 *     make render-deployment         # write
 *     make render-deployment-check   # fail if out of date (CI)
 *
 * `generated.yaml` is written whole and must not be hand-edited. The rest
 * of each overlay is left alone: structure is genuinely hand-written.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

// Under vitest `import.meta.url` is not always a file: URL, so fall back
// to the working directory rather than throwing at import time.
// Pass the URL as a string, not a URL object: under jsdom the global URL
// is jsdom's, and fileURLToPath rejects it as "must be of scheme file".
const MODULE_DIR = import.meta.url.startsWith('file:')
  ? dirname(fileURLToPath(import.meta.url))
  : join(process.cwd(), 'scripts');
const REPO_ROOT = join(MODULE_DIR, '..');
const VALUES = join(REPO_ROOT, 'config', 'ui', 'deployment', 'values.yaml');
const GENERATED_FILE = 'generated.yaml';
const NAME = 'template-ui';

const BANNER = [
  '# Generated by scripts/render-deployment.ts — DO NOT EDIT.',
  '# Source: config/ui/deployment/values.yaml',
  '# Regenerate with `make render-deployment`.',
  '',
].join('\n');

/** Resources the kind overlay does not have, so must not be patched there. */
const TARGETS: Record<string, { route: boolean; build: boolean }> = {
  openshift: { route: true, build: true },
  kind: { route: false, build: false },
};

type Values = Record<string, any>;

function isPlainObject(value: unknown): value is Record<string, any> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function merge(base: Values, override: Values): Values {
  const out: Values = { ...base };
  for (const [key, value] of Object.entries(override)) {
    out[key] =
      isPlainObject(value) && isPlainObject(out[key]) ? merge(out[key], value) : value;
  }
  return out;
}

/**
 * Values as they apply to one overlay.
 *
 * `targets:` is the escape hatch for real environment differences — a
 * laptop cluster does not want two replicas. Without it a single shared
 * file would force every overlay to be identical, and people would go
 * back to editing manifests by hand.
 */
function forTarget(values: Values, target: string): Values {
  const overrides = values.targets?.[target] ?? {};
  const merged = merge(values, overrides);
  delete merged.targets;
  return merged;
}

function resources(block: Values | undefined): Values | null {
  if (!block) return null;
  const out: Values = {};
  for (const kind of ['requests', 'limits']) {
    const fields: Values = {};
    for (const field of ['memory', 'cpu']) {
      if (block[kind]?.[field] !== undefined) fields[field] = String(block[kind][field]);
    }
    if (Object.keys(fields).length) out[kind] = fields;
  }
  return Object.keys(out).length ? out : null;
}

function probes(spec: Values | undefined, port: number): Values {
  const out: Values = {};
  for (const [name, key] of [
    ['liveness', 'livenessProbe'],
    ['readiness', 'readinessProbe'],
  ] as const) {
    const probe = spec?.[name];
    if (!probe) continue;
    const fragment: Values = {};
    // httpGet needs both path and port: strategic merge replaces the
    // whole httpGet block, so omitting the port would drop it.
    if (probe.path) fragment.httpGet = { path: probe.path, port };
    for (const field of [
      'initialDelaySeconds',
      'periodSeconds',
      'timeoutSeconds',
      'failureThreshold',
    ]) {
      if (probe[field] !== undefined) fragment[field] = probe[field];
    }
    out[key] = fragment;
  }
  return out;
}

/**
 * Replicas, resources and probes on the UI Deployment.
 *
 * Containers merge by name, so `name` is load-bearing — without it
 * strategic merge appends a second container instead of editing the one
 * that is there.
 */
function deploymentPatch(values: Values): Values | null {
  const port = Number(values.container?.port ?? values.networking?.service?.port ?? 8080);
  const container: Values = { name: NAME };

  const res = resources(values.resources);
  if (res) container.resources = res;
  Object.assign(container, probes(values.probes, port));
  if (values.container?.port !== undefined) {
    container.ports = [{ containerPort: port, name: 'http', protocol: 'TCP' }];
  }

  const spec: Values = {};
  if (values.app?.replicas !== undefined) spec.replicas = Number(values.app.replicas);
  if (Object.keys(container).length > 1) {
    spec.template = { spec: { containers: [container] } };
  }

  if (!Object.keys(spec).length) return null;
  return { apiVersion: 'apps/v1', kind: 'Deployment', metadata: { name: NAME }, spec };
}

function servicePatch(values: Values): Values | null {
  const service = values.networking?.service;
  if (!service) return null;
  const spec: Values = {};
  if (service.type) spec.type = String(service.type);
  if (service.port !== undefined) {
    // ports is a list, so strategic merge replaces it wholesale rather
    // than merging element-wise. Emit the complete entry or nothing.
    spec.ports = [
      {
        name: 'http',
        port: Number(service.port),
        targetPort: Number(service.port),
        protocol: 'TCP',
      },
    ];
  }
  if (!Object.keys(spec).length) return null;
  return { apiVersion: 'v1', kind: 'Service', metadata: { name: NAME }, spec };
}

function routePatch(values: Values): Values | null {
  const route = values.networking?.route;
  if (!route?.enabled) return null;
  const tls = route.tls ?? {};
  if (!Object.keys(tls).length) return null;
  return {
    apiVersion: 'route.openshift.io/v1',
    kind: 'Route',
    metadata: { name: NAME },
    spec: { tls: Object.fromEntries(Object.entries(tls).map(([k, v]) => [k, String(v)])) },
  };
}

function buildConfigPatch(values: Values): Values | null {
  const res = resources(values.build?.resources);
  if (!res) return null;
  return {
    apiVersion: 'build.openshift.io/v1',
    kind: 'BuildConfig',
    metadata: { name: NAME },
    spec: { resources: res },
  };
}

export function renderPatches(values: Values, target: string): string {
  const caps = TARGETS[target];
  const docs = [
    deploymentPatch(values),
    servicePatch(values),
    caps.route ? routePatch(values) : null,
    caps.build ? buildConfigPatch(values) : null,
  ].filter((d): d is Values => d !== null);

  const body = docs
    .map((doc) => yaml.dump(doc, { noRefs: true, lineWidth: -1 }))
    .join('---\n');
  return BANNER + body;
}

/** Make sure the overlay actually applies generated.yaml. */
export function ensurePatchReference(kustomization: string): string {
  if (kustomization.includes(`path: ${GENERATED_FILE}`)) return kustomization;
  if (/^patches:$/m.test(kustomization)) {
    return kustomization.replace(/^patches:$/m, `patches:\n  - path: ${GENERATED_FILE}`);
  }
  return `${kustomization.replace(/\n+$/, '')}\n\npatches:\n  - path: ${GENERATED_FILE}\n`;
}

/** Every file this would write, mapped to its intended contents. */
export function plan(values: Values): Map<string, string> {
  const out = new Map<string, string>();
  for (const target of Object.keys(TARGETS)) {
    const overlay = join(REPO_ROOT, 'deployment', 'overlays', target);
    if (!existsSync(overlay)) continue;

    const resolved = forTarget(values, target);
    out.set(join(overlay, GENERATED_FILE), renderPatches(resolved, target));

    const kustomization = join(overlay, 'kustomization.yaml');
    out.set(kustomization, ensurePatchReference(readFileSync(kustomization, 'utf8')));
  }
  return out;
}

export function loadValues(): Values {
  return (yaml.load(readFileSync(VALUES, 'utf8')) ?? {}) as Values;
}

function main(): number {
  const check = process.argv.includes('--check');
  const wanted = plan(loadValues());

  const stale = [...wanted].filter(
    ([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text,
  );

  if (check) {
    if (stale.length) {
      console.error('Deployment overlays are out of date:');
      for (const [path] of stale) console.error(`  ${relative(REPO_ROOT, path)}`);
      console.error('\nRun `make render-deployment`.');
      return 1;
    }
    console.log('Deployment overlays are up to date.');
    return 0;
  }

  for (const [path, text] of wanted) writeFileSync(path, text);
  if (stale.length) {
    console.log(`Rendered ${stale.length} file(s) from config/ui/deployment/values.yaml:`);
    for (const [path] of stale) console.log(`  ${relative(REPO_ROOT, path)}`);
  } else {
    console.log('Already up to date.');
  }
  return 0;
}

const invokedDirectly =
  import.meta.url.startsWith('file:') &&
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1]);

if (invokedDirectly) {
  process.exit(main());
}
